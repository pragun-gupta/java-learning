public class mathsops {
    public static void main(String [] args){
        //System.out.println(Math.PI);  // pi number
        //System.out.println(Math.E);   // eulers number

        double results;
        results = Math.pow(2,3);  // power  a^b
        results = Math.abs(-5);  // absolute power
        results = Math.sqrt(9);   // square root
        results = Math.round(3.14);   // round off
        results = Math.ceil(3.14);    //round Up
        results = Math.floor(3.99);   // round down
        results = Math.max(10,20);   // Max number
        results = Math.min(10,20);   // Min number


        System.out.println(results);
    }
}
